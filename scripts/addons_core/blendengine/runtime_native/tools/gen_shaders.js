// Generates src/be_shaders.h from the GLSL ES 3.00 sources in
// runtime_web/blendengine_runtime.js, so the web and native runtimes share
// one set of shaders.
//
//   node tools/gen_shaders.js
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', '..', 'runtime_web', 'blendengine_runtime.js'), 'utf8');
const re = /const ([A-Z0-9_]+) = `([\s\S]*?)`;/g;
const shaders = {};
let m;
while ((m = re.exec(src))) shaders[m[1]] = m[2];
const resolve = (text) => text.replace(/\$\{([A-Z0-9_]+)\}/g, (_, name) => {
  if (!(name in shaders)) throw new Error('unknown shader include ' + name);
  return resolve(shaders[name]);
});
let out = '/* Generated by tools/gen_shaders.js from runtime_web/blendengine_runtime.js. Do not edit. */\n#pragma once\n\n';
for (const [name, text] of Object.entries(shaders)) {
  if (!text.startsWith('#version')) continue;
  const body = resolve(text).split('\n').map((l) => '  "' + l.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '\\n"').join('\n');
  out += `static const char BE_${name}[] =\n${body};\n\n`;
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'be_shaders.h'), out);
console.log('wrote', Object.keys(shaders).filter((k) => shaders[k].startsWith('#version')).join(' '));
